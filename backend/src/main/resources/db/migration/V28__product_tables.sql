-- ─── 상품 테이블 ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS product (
    product_id      VARCHAR(30)     NOT NULL,
    category        VARCHAR(50)     NOT NULL,
    sub_category    VARCHAR(50),
    product_nm      VARCHAR(200)    NOT NULL,
    brand           VARCHAR(100)    NOT NULL,
    model_no        VARCHAR(100),
    price           DECIMAL(15,0)   NOT NULL,
    sale_price      DECIMAL(15,0),
    stock_qty       INT             DEFAULT 0,
    release_date    DATE,
    status          VARCHAR(20)     DEFAULT 'ON_SALE',
    thumbnail_url   VARCHAR(500),
    rating          DECIMAL(3,1),
    review_cnt      INT             DEFAULT 0,
    created_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_product PRIMARY KEY (product_id)
);

-- ─── 상품 상세 테이블 ──────────────────────────────────────────
CREATE TABLE IF NOT EXISTS product_detail (
    detail_id       BIGINT          AUTO_INCREMENT NOT NULL,
    product_id      VARCHAR(30)     NOT NULL,
    spec_group      VARCHAR(100),
    spec_key        VARCHAR(100)    NOT NULL,
    spec_value      VARCHAR(2000)   NOT NULL,
    sort_order      INT             DEFAULT 0,
    description     TEXT,
    CONSTRAINT pk_product_detail PRIMARY KEY (detail_id),
    CONSTRAINT fk_product_detail_product FOREIGN KEY (product_id) REFERENCES product(product_id)
);

CREATE INDEX idx_product_detail_pid  ON product_detail(product_id);
CREATE INDEX idx_product_category    ON product(category, sub_category);
CREATE INDEX idx_product_status      ON product(status);
CREATE INDEX idx_product_price       ON product(price, sale_price);

